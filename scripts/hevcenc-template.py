#!/usr/bin/env python3
"""hevcenc-template.py: src/hevcenctmpl.h from NVIDIA's Linux driver HEVC setups at -preset p7 -tune hq
(docs/traces/quality-linux vp7 / vp7b, T7.08): the ME (192 bytes at 0x800), MD (128 at 0x3800) and quant (16 at 0x5800)
control blocks of an IDR, a P and a B picture. They do not depend on the picture size (vp7k, 4K, has the same)."""
import sys
d = sys.argv[1] if len(sys.argv) > 1 else "docs/traces/quality-linux"
def blk(path, off, n): return open(path, "rb").read()[off:off + n]
def arr(name, b):
    s = "static const uint8_t %s[%d] = {\n" % (name, len(b))
    for i in range(0, len(b), 24): s += "    " + ", ".join("0x%02x" % x for x in b[i:i + 24]) + ",\n"
    return s + "};\n"
src = {"idr": d + "/vp7/dump/exec1-710.bin", "p": d + "/vp7/dump/exec2-710.bin", "b": d + "/vp7b/dump/exec3-710.bin"}
out = "// hevcenctmpl.h: generated by scripts/hevcenc-template.py from docs/traces/quality-linux (NVIDIA's Linux driver 580.105.08,\n"
out += "// hevc_nvenc -preset p7 -tune hq; T7.08): ME / MD / quant control blocks per picture type, used in quality mode.\n#pragma once\n#include <stdint.h>\n"
for t, p in src.items():
    out += arr("hevc_p7_me_" + t, blk(p, 0x800, 192)) + arr("hevc_p7_md_" + t, blk(p, 0x3800, 128))
out += arr("hevc_p7_q", blk(src["p"], 0x5800, 16))
open("src/hevcenctmpl.h", "w").write(out)
