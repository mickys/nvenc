#!/usr/bin/env python3
"""av1enc-template.py: src/av1enctmpl.h from the traced NVIDIA Linux driver AV1 setups (docs/traces/av1-linux, M12):
the key and P picture setups of a 256x128 encode (Ada layout, 800 bytes, plus the tile control at 0x800) and the RC
process words the driver writes before the first frame."""
import struct, sys
d = sys.argv[1] if len(sys.argv) > 1 else "docs/traces/av1-linux"
def arr(name, b):
    s = "static const uint8_t %s[%d] = {\n" % (name, len(b))
    for i in range(0, len(b), 24): s += "    " + ", ".join("0x%02x" % x for x in b[i:i + 24]) + ",\n"
    return s + "};\n"
key = open(d + "/key-256x128-setup.bin", "rb").read(); p = open(d + "/p-256x128-setup.bin", "rb").read()
rc = open(d + "/key-256x128-rcprocess.bin", "rb").read()[:128]
out = "// av1enctmpl.h: generated by scripts/av1enc-template.py from docs/traces/av1-linux (NVIDIA's Linux driver 580.105.08 encoding\n"
out += "// AV1 at 256x128, observed with trace-linux/nvtrace.so; M12). Picture setups in Ada's layout (nvenc_av1_drv_pic_setup_s with\n"
out += "// a fourth 32-byte surface config at 0x64), the tile control at 0x800, and the driver's initial RC process words.\n#pragma once\n#include <stdint.h>\n"
out += arr("av1_tmpl_key", key[:0x320]) + arr("av1_tmpl_key_tile", key[0x800:0x820])
out += arr("av1_tmpl_p", p[:0x320]) + arr("av1_tmpl_p_tile", p[0x800:0x820]) + arr("av1_tmpl_rcprocess", rc)
open("src/av1enctmpl.h", "w").write(out)
